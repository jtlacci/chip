#!/usr/bin/env python3
"""Render the declared sibling-dependency graph as Mermaid, using only the standard library."""

from __future__ import annotations

import argparse
import ast
from pathlib import Path
import sys
from typing import Any


def assigned_literal(tree: ast.Module, name: str) -> Any:
    """Return the literal assigned to a module-level name, or None."""
    for node in tree.body:
        value = None
        if isinstance(node, ast.Assign) and any(
            isinstance(target, ast.Name) and target.id == name for target in node.targets
        ):
            value = node.value
        elif isinstance(node, ast.AnnAssign) and isinstance(node.target, ast.Name):
            if node.target.id == name:
                value = node.value
        if value is not None:
            try:
                return ast.literal_eval(value)
            except (TypeError, ValueError):
                return None
    return None


def read_contract(brick: Path) -> tuple[dict[str, str], tuple[str, ...]]:
    """Read one brick's declared sibling dependencies and owned state."""
    path = brick / "contract.py"
    if not path.is_file():
        return {}, ()
    try:
        tree = ast.parse(path.read_text(encoding="utf-8"), filename=str(path))
    except (OSError, SyntaxError):
        return {}, ()

    dependencies = assigned_literal(tree, "SIBLING_DEPENDENCIES")
    owned_state = assigned_literal(tree, "OWNED_STATE")
    if not isinstance(dependencies, dict):
        dependencies = {}
    if not isinstance(owned_state, (tuple, list)):
        owned_state = ()
    return (
        {
            name: mode
            for name, mode in dependencies.items()
            if isinstance(name, str) and isinstance(mode, str)
        },
        tuple(item for item in owned_state if isinstance(item, str) and item),
    )


def escape(text: str) -> str:
    """Escape one label segment for a quoted Mermaid node label."""
    return text.replace("\\", "\\\\").replace('"', "&quot;")


def node_label(name: str, owned_state: tuple[str, ...]) -> str:
    """Build the node label, listing the state the brick owns."""
    lines = [escape(name), *(escape(resource) for resource in owned_state)]
    return "<br/>".join(lines)


def render(contracts: dict[str, tuple[dict[str, str], tuple[str, ...]]]) -> str:
    """Render the declared graph as a Mermaid flowchart."""
    names = sorted(contracts)
    depended_on = {
        dependency
        for dependencies, _ in contracts.values()
        for dependency in dependencies
        if dependency in contracts
    }

    lines = [
        "%% Generated by tools/graph_bricks.py. Solid arrow: orchestrated. Dashed arrow: eventual.",
        "flowchart TD",
    ]
    for name in names:
        _, owned_state = contracts[name]
        lines.append(f'    {name}["{node_label(name, owned_state)}"]')

    edges = [
        f"    {name} {'-.->' if mode == 'eventual' else '-->'} {dependency}"
        for name in names
        for dependency, mode in sorted(contracts[name][0].items())
    ]
    if edges:
        lines.append("")
        lines.extend(edges)

    top_level = [name for name in names if name not in depended_on]
    if top_level and len(top_level) != len(names):
        lines.append("")
        lines.append("    classDef topLevel stroke-width:3px")
        lines.append(f"    class {','.join(top_level)} topLevel")
    return "\n".join(lines) + "\n"


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--root", type=Path, default=Path(__file__).resolve().parents[1])
    root = parser.parse_args().root.resolve()

    bricks = root / "bricks"
    if not bricks.is_dir():
        print(f"{bricks}: bricks directory is missing", file=sys.stderr)
        return 1

    contracts = {
        path.name: read_contract(path)
        for path in sorted(bricks.iterdir())
        if path.is_dir() and not path.name.startswith((".", "__"))
    }
    if not contracts:
        print(f"{bricks}: no bricks to graph", file=sys.stderr)
        return 1

    print(render(contracts), end="")
    return 0


if __name__ == "__main__":
    sys.exit(main())
